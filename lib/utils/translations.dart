extension LocalizationExtension on BuildContext {
  String tr(String key, {List<String> args = const []}) {
    final settingsState = watch<SettingsBloc>().state;
    String lang = 'es';
    if (settingsState is SettingsLoaded) {
      lang = settingsState.data.language;
    }
    return Translations.get(key, lang, args: args);
  }
}
